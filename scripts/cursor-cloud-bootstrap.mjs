import { constants, realpathSync } from "node:fs";
import { lstat, open } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { listSecretsRaw } from "./infisical-fetch.mjs";
import { withCursorOutputTransaction } from "./cursor-cloud-output.mjs";

const HEADER = "# Generated by scripts/cursor-cloud-start.sh -- do not edit.\n";
const outputHelper = fileURLToPath(new URL("./cursor-cloud-output.mjs", import.meta.url)).replace(/'/g, "'\\''");
const SOURCE_SCRIPT = `${HEADER}{ set +x; } 2>/dev/null
set +o xtrace
export -n SHELLOPTS BASH_XTRACEFD 2>/dev/null || true
_botfleet_environment="$(node '${outputHelper}' --read-environment "\${HOME}")" || return 1
set -a
eval "\${_botfleet_environment}"
unset _botfleet_environment
set +a
`;
const digest = (value) => createHash("sha256").update(value).digest("hex");
const metadataKeys = new Set(["INFISICAL_PROJECT_ID", "INFISICAL_ENV", "INFISICAL_DOMAIN"]);

export function parseCursorMetadata(text) {
  const result = {};
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const match = /^([A-Z_][A-Z0-9_]*)=(.*)$/.exec(line);
    if (!match || !metadataKeys.has(match[1]) || Object.hasOwn(result, match[1])) throw new Error("Invalid metadata.");
    let value = match[2];
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    if (!/^[A-Za-z0-9_./:-]+$/.test(value)) throw new Error("Metadata must contain literal values.");
    result[match[1]] = value;
  }
  return result;
}

function pinnedOrigin(value) {
  const url = new URL(value);
  if (url.protocol !== "https:" || url.username || url.password || url.origin !== value ||
      url.search || url.hash) throw new Error("An exact HTTPS origin is required.");
  return url.origin;
}

async function readMetadataFile(path) {
  const info = await lstat(path).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (!info) return null;
  if (!info.isFile() || info.isSymbolicLink() || (process.getuid && info.uid !== process.getuid())) throw new Error("Unsafe metadata file.");
  const file = await open(path, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
  try {
    const current = await file.stat();
    if (!current.isFile() || (process.getuid && current.uid !== process.getuid())) throw new Error("Unsafe metadata file.");
    return await file.readFile("utf8");
  } finally { await file.close(); }
}

export async function prepareCursorEnvironment({
  env = process.env, homeDir = env.HOME || homedir(), metadataFile = null,
  operations, lockWaitMs, fetchImpl = fetch,
  log = (message) => console.log(`[cursor-cloud-start] ${message}`),
} = {}) {
  return withCursorOutputTransaction({ homeDir, log, operations, lockWaitMs }, async ({ guard, invalidate, publish }) => {
    guard();
    const token = (env.INFISICAL_TOKEN ?? "").trim();
    const secretPath = env.INFISICAL_SECRET_PATH ?? "";
    const declaredNames = (env.BOTFLEET_CURSOR_SECRET_NAMES ?? "").trim();
    const trustedOrigin = (env.BOTFLEET_CURSOR_INFISICAL_ORIGIN ?? "").trim();
    if (!token || !secretPath.trim() || !declaredNames || !trustedOrigin) {
      await invalidate();
      log("Optional binding, folder, names or trusted origin absent; verified owned environment cleared.");
      return { state: "disabled", count: 0 };
    }
    try {
      const siteUrl = pinnedOrigin(trustedOrigin);
      const names = declaredNames.split(",").map((name) => name.trim());
      if (names.some((name) => !/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) ||
          new Set(names).size !== names.length) throw new Error("Declared names are invalid.");
      const metadataText = metadataFile ? await readMetadataFile(metadataFile) : null;
      guard();
      const metadata = metadataText === null ? {} : parseCursorMetadata(metadataText);
      const setting = (name) => env[name] ?? metadata[name];
      for (const origin of [env.INFISICAL_DOMAIN, metadata.INFISICAL_DOMAIN]) {
        if (origin && pinnedOrigin(origin) !== siteUrl) throw new Error("Metadata origin differs from trusted binding.");
      }
      const projectId = (setting("INFISICAL_PROJECT_ID") ?? "").trim();
      const environment = setting("INFISICAL_ENV") || "prod";
      if (!projectId) throw new Error("Project metadata is missing.");
      const pinnedFetch = async (url, init) => {
        guard();
        if (new URL(url).origin !== siteUrl) throw new Error("Request left the trusted origin.");
        const response = await fetchImpl(url, { ...init, redirect: "error" });
        guard();
        return response;
      };
      let incomplete = false;
      const values = await listSecretsRaw({ siteUrl, token, projectId, environment, secretPath, names, fetchImpl: pinnedFetch,
        log: () => { incomplete = true; } });
      guard();
      if (incomplete || names.some((name) => !values.has(name))) throw new Error("Declared values are unavailable.");
      const entries = names.map((name) => [name, values.get(name)]);
      if (entries.some(([, value]) => /\$\{[^}]*\}/.test(value))) throw new Error("References are unavailable.");
      const quote = (value) => "'" + value.replace(/'/g, "'\\''") + "'";
      const body = HEADER + entries.map(([key, value]) => `${key}=${quote(value)}\n`).join("");
      const manifest = JSON.stringify({ owner: "botfleet-cursor-bootstrap", version: 1,
        scopeFingerprint: digest(JSON.stringify({ siteUrl, projectId, environment, secretPath, names })),
        files: { "BotFleet.env": digest(body), "BotFleet.source.sh": digest(SOURCE_SCRIPT) } }) + "\n";
      await publish(body, SOURCE_SCRIPT, manifest);
      log(`Wrote ${entries.length} declared environment names through the pinned read-only binding.`);
      return { state: "written", count: entries.length };
    } catch {
      try { await invalidate(); }
      catch {
        log("Unverified or changed generated environment preserved; bootstrap unavailable.");
        return { state: "unavailable", count: 0 };
      }
      log("Infisical bootstrap unavailable; verified owned environment cleared.");
      return { state: "unavailable", count: 0 };
    }
  });
}

function isEntryModule() {
  try { return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); }
  catch { return false; }
}
if (isEntryModule()) {
  const root = dirname(dirname(fileURLToPath(import.meta.url)));
  prepareCursorEnvironment({ metadataFile: join(root, ".cursor/infisical.env") }).catch(() => {
    console.error("[cursor-cloud-start] Cannot verify generated environment ownership safely.");
    process.exitCode = 1;
  });
}
